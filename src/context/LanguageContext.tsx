/**
 * Adds a set of texts to the dictionary. The admin's texts live in src/i18n/adminTranslations.ts and are added when
 * the admin loads (src/i18n/admin.ts, imported by AdminShell), so the client page's bundle never carries them.
 */
export function addTranslations(extra: Record<Lang, Record<string, string>>): void {
  Object.assign(translations.fr, extra.fr);
  Object.assign(translations.ar, extra.ar);
}

const LanguageContext = createContext<LanguageContextValue | undefined>(undefined);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>('fr');
  const dir = lang === 'ar' ? 'rtl' : 'ltr';

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);

  const toggleLang = useCallback(() => {
    setLang((prev) => (prev === 'fr' ? 'ar' : 'fr'));
  }, []);

  const t = useCallback(
    (key: string) => translations[lang][key] ?? translations.fr[key] ?? key,
    [lang]
  );

  return (
    <LanguageContext.Provider value={{ lang, dir, setLang, toggleLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

// eslint-disable-next-line react-refresh/only-export-components
export function useLang() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLang must be used within LanguageProvider');
  return ctx;
}
